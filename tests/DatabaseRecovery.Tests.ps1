#requires -Version 5.1
param([string]$ProjectName, [string]$EnvironmentFile)
$ErrorActionPreference = 'Stop'
$repository = Split-Path -Parent $PSScriptRoot
. (Join-Path $repository 'scripts/Database.Common.ps1')
$context = Get-KynexDatabaseContext -ProjectName $ProjectName -EnvironmentFile $EnvironmentFile
$suffix = [Guid]::NewGuid().ToString('N').Substring(0,12)
$source = 'kynex_backup_test_' + $suffix
$destination = 'kynex_restore_test_' + $suffix
$corruptDestination = 'kynex_restore_test_' + [Guid]::NewGuid().ToString('N').Substring(0,12)
$outputDirectory = Join-Path $repository ('.local/recovery-tests/' + $suffix + '/copia con espacios')
$checks = New-Object 'System.Collections.Generic.List[string]'
function Assert-RecoveryCheck {
    param([bool]$Condition, [string]$Description)
    if (!$Condition) { throw ('Fallo: ' + $Description) }
    $checks.Add($Description)
    Write-Host ('OK: ' + $Description)
}
function Assert-RecoveryRejected {
    param([scriptblock]$Operation, [string]$Pattern, [string]$Description)
    $rejected = $false
    try { & $Operation | Out-Null } catch { if ($_.Exception.Message -notmatch $Pattern) { throw }; $rejected = $true }
    Assert-RecoveryCheck $rejected $Description
}
function Get-FixtureFingerprint {
    param([string]$Database)
    $sql = "select md5((select string_agg(row_to_json(u)::text,'|' order by id) from app_user u)||(select string_agg(row_to_json(p)::text,'|' order by id) from product p)||(select string_agg(row_to_json(o)::text,'|' order by id) from sample_purchase o));"
    return (Invoke-KynexSql $context $Database $sql).Trim()
}
$sourceCreated = $false
try {
    Invoke-KynexDocker $context @('exec','-T','postgres','createdb','-U',$context.User,'--template=template0','--encoding=UTF8',$source) | Out-Null
    $sourceCreated = $true
    $schema = @'
create table app_user(id bigint generated by default as identity primary key, name text not null);
create table product(id bigint generated by default as identity primary key, name text not null, price numeric(12,2) not null);
create table sample_purchase(id bigint generated by default as identity primary key, owner_id bigint references app_user(id), product_id bigint references product(id));
create table refresh_session(id uuid primary key, revoked boolean not null default false);
insert into app_user(name) values ('Mun' || chr(241) || 'oz ' || chr(128170));
insert into product(name,price) values ('Prote' || chr(237) || 'na',19990.50);
insert into sample_purchase(owner_id,product_id) values (1,1);
insert into refresh_session(id) values ('11111111-1111-4111-8111-111111111111');
'@
    Invoke-KynexSql $context $source $schema | Out-Null
    $fingerprint = Get-FixtureFingerprint $source
    $backup = & (Join-Path $repository 'scripts/Backup-Database.ps1') -Database $source -OutputDirectory ($outputDirectory + [IO.Path]::DirectorySeparatorChar) -ProjectName $ProjectName -EnvironmentFile $EnvironmentFile
    Assert-RecoveryCheck ((Test-Path -LiteralPath $backup.MetadataPath) -and (Get-FileHash -LiteralPath $backup.BackupPath -Algorithm SHA256).Hash -eq $backup.Sha256) 'El archivo conserva su SHA-256 y sus metadatos.'
    $restored = & (Join-Path $repository 'scripts/Restore-Database.ps1') -BackupPath $backup.BackupPath -Database $destination -ProjectName $ProjectName -EnvironmentFile $EnvironmentFile
    Assert-RecoveryCheck ($restored.Database -eq $destination -and (Get-FixtureFingerprint $destination) -eq $fingerprint) 'Se recuperan datos Unicode, importes y relaciones sin cambios.'
    Assert-RecoveryCheck ((Get-FixtureFingerprint $source) -eq $fingerprint) 'Los datos originales permanecen intactos.'
    Assert-RecoveryCheck ((Invoke-KynexSql $context $destination 'select count(*) from refresh_session where not revoked;').Trim() -eq '0') 'Las sesiones restauradas quedan revocadas.'
    Assert-RecoveryCheck ((Invoke-KynexSql $context $source 'select count(*) from refresh_session where not revoked;').Trim() -eq '1') 'Las sesiones originales permanecen activas.'
    $nextId = (Invoke-KynexSql $context $destination "insert into product(name,price) values ('Nuevo producto',1) returning id;").Trim()
    Assert-RecoveryCheck ($nextId -eq '2') 'La secuencia continua desde el identificador restaurado.'
    Assert-RecoveryRejected { & (Join-Path $repository 'scripts/Restore-Database.ps1') -BackupPath $backup.BackupPath -Database $destination -ProjectName $ProjectName -EnvironmentFile $EnvironmentFile } 'ya existe' 'Una base existente no se sobrescribe.'
    Assert-RecoveryRejected { & (Join-Path $repository 'scripts/Restore-Database.ps1') -BackupPath $backup.BackupPath -Database $source -ProjectName $ProjectName -EnvironmentFile $EnvironmentFile } 'kynex_restore_' 'La base de origen no se utiliza como destino.'
    Assert-RecoveryRejected { Invoke-KynexSql $context $destination 'insert into sample_purchase(owner_id,product_id) values (1,99999);' } 'foreign key|clave for' 'Las claves foraneas siguen protegiendo las relaciones.'
    $damagedPath = Join-Path $outputDirectory 'damaged.dump'
    [IO.File]::Copy($backup.BackupPath,$damagedPath,$false)
    [IO.File]::Copy($backup.MetadataPath,($damagedPath + '.json'),$false)
    $bytes = [IO.File]::ReadAllBytes($damagedPath); $bytes[$bytes.Length-1] = $bytes[$bytes.Length-1] -bxor 1
    [IO.File]::WriteAllBytes($damagedPath,$bytes)
    Assert-RecoveryRejected { & (Join-Path $repository 'scripts/Restore-Database.ps1') -BackupPath $damagedPath -Database $corruptDestination -ProjectName $ProjectName -EnvironmentFile $EnvironmentFile } 'SHA-256' 'Un respaldo alterado se rechaza antes de crear una base.'
    $createdByFailure = (Invoke-KynexSql $context 'postgres' ("select count(*) from pg_database where datname='$corruptDestination';")).Trim()
    Assert-RecoveryCheck ($createdByFailure -eq '0') 'El rechazo de integridad no deja una base creada.'
    [pscustomobject]@{ Passed=$checks.Count; Failed=0; PowerShell=$PSVersionTable.PSVersion.ToString() }
} finally {
    # Solo se retiran las bases de prueba generadas por esta ejecucion; nunca la base del proyecto.
    foreach ($name in @($source,$destination,$corruptDestination)) {
        if ($name -cnotmatch '^kynex_(backup|restore)_test_[a-f0-9]{12}$') { throw 'Nombre de limpieza de pruebas no reconocido.' }
        if ($sourceCreated) { Invoke-KynexDocker $context @('exec','-T','postgres','dropdb','-U',$context.User,'--if-exists',$name) | Out-Null }
    }
}
