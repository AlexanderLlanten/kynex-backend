-- Los envíos anteriores conservan sus notas privadas y no se asignan por coincidencia de correo.
alter table contact_message add column owner_id bigint references app_user(id);
create index contact_owner_inbox on contact_message(owner_id, created_at desc, id desc);
create table contact_reply (
    id bigint generated by default as identity primary key,
    message_id bigint not null references contact_message(id),
    reply_key uuid not null unique,
    actor_id bigint references app_user(id) on delete set null,
    actor_name varchar(151) not null,
    text varchar(2000) not null check(length(trim(text)) > 0),
    created_at timestamptz not null
);
create index contact_reply_history on contact_reply(message_id, id);
