CREATE TABLE shopping_cart (
    user_id BIGINT PRIMARY KEY REFERENCES app_user(id),
    revision BIGINT NOT NULL DEFAULT 0 CHECK(revision >= 0)
);
CREATE TABLE cart_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_user_id BIGINT NOT NULL REFERENCES shopping_cart(user_id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    quantity INTEGER NOT NULL CHECK(quantity > 0),
    UNIQUE(cart_user_id, product_id)
);
CREATE TABLE cart_merge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    request_id UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    UNIQUE(user_id, request_id)
);
CREATE TABLE purchase_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_user(id),
    request_id UUID NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','CONFIRMED','PREPARING','SHIPPED','DELIVERED','CANCELLED','EXPIRED')),
    customer_name VARCHAR(151) NOT NULL,
    customer_email VARCHAR(100) NOT NULL,
    recipient VARCHAR(150) NOT NULL,
    region VARCHAR(100) NOT NULL,
    commune VARCHAR(100) NOT NULL,
    address VARCHAR(300) NOT NULL,
    subtotal NUMERIC(28,2) NOT NULL CHECK(subtotal >= 0),
    shipping NUMERIC(28,2) NOT NULL CHECK(shipping >= 0),
    total NUMERIC(28,2) NOT NULL CHECK(total = subtotal + shipping),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    stock_restored BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE(owner_id, request_id)
);
CREATE INDEX purchase_order_owner_idx ON purchase_order(owner_id, id DESC);
CREATE TABLE order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES purchase_order(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    cart_line_id BIGINT NOT NULL,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    image VARCHAR(1000) NOT NULL,
    price NUMERIC(14,2) NOT NULL CHECK(price >= 0),
    quantity INTEGER NOT NULL CHECK(quantity > 0)
);
CREATE TABLE payment_attempt (
    id UUID PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES purchase_order(id),
    request_id UUID NOT NULL,
    scenario VARCHAR(30) NOT NULL CHECK(scenario IN ('APPROVE','REJECT','CANCEL','EXPIRE','TECHNICAL_ERROR')),
    status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','CANCELLED','EXPIRED','ERROR')),
    amount NUMERIC(28,2) NOT NULL CHECK(amount >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    reversed BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(order_id, request_id)
);
CREATE UNIQUE INDEX one_approved_payment_per_order ON payment_attempt(order_id) WHERE status = 'APPROVED';
CREATE TABLE order_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES purchase_order(id),
    actor_id BIGINT NOT NULL REFERENCES app_user(id),
    status VARCHAR(20) NOT NULL,
    note VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
