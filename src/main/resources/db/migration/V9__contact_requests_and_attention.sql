-- La recepción pública es idempotente; el contenido original y la atención se conservan.
create table contact_message (
    id bigint generated by default as identity primary key,
    submission_key uuid not null unique,
    name varchar(100) not null check (length(trim(name)) > 0),
    email varchar(100) not null,
    comment varchar(500) not null check (length(trim(comment)) > 0),
    status varchar(20) not null default 'PENDIENTE' check (status in ('PENDIENTE','EN_ATENCION','RESUELTA')),
    note varchar(1000) not null default '',
    version bigint not null default 0,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    check (status <> 'RESUELTA' or length(trim(note)) > 0)
);
create index contact_inbox on contact_message (status, created_at desc, id desc);
create table contact_event (
    id bigint generated by default as identity primary key,
    message_id bigint not null references contact_message(id),
    actor_id bigint references app_user(id) on delete set null,
    actor_name varchar(151) not null,
    status varchar(20) not null check (status in ('PENDIENTE','EN_ATENCION','RESUELTA')),
    note varchar(1000) not null,
    created_at timestamptz not null
);
create index contact_event_history on contact_event(message_id, id);
